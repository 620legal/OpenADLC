/**
 * What the host ran on before an apply: its name, and the module's
 * `host_rollout` (its cloud-init and the database URL), each null when the
 * state had none.
 */
export interface HostBeforeApply {
  host: string | null;
  rollout: string | null;
}

/**
 * A name as GCE allows instance names. Nothing that fails this is a host, and
 * nothing that fails this goes on a gcloud command line.
 */
export const INSTANCE_NAME = /^[a-z]([-a-z0-9]{0,61}[a-z0-9])?$/;

/**
 * Whether an apply has to reset the host. Container-Optimized OS applies
 * cloud-init at boot, and hostd reads the database URL only when it starts: a
 * host that was only restarted ran the old prepare script against the new URL,
 * found no CA where the URL names one, and lost the database. Not for a host
 * this apply made, which booted on the new ones. A host whose state predates
 * `host_rollout` has none before, and is reset once.
 *
 * Only for a host that is known by name: when the outputs could not be read —
 * an apply that ends in an error writes none — there is nothing to decide
 * with, and this run does not decide: `afterTerraform` says so and, for a host
 * it knows, prints the reset to run by hand. `outputAnswer` turns everything
 * unusable into null, and a name that is not one is refused here too;
 * `afterTerraform` checks it once more, last, before it puts it on a gcloud
 * command line.
 */
export function hostNeedsReset(before: HostBeforeApply, after: string | null): boolean {
  return before.host !== null && INSTANCE_NAME.test(before.host) && after !== null && before.rollout !== after;
}

/**
 * Whether this command has to reset the host, including an apply that failed.
 *
 * Terraform can commit the new `host_rollout` and then fail on a later
 * resource. The reset ran only after an apply that exited 0, so a host whose
 * database URL had already changed kept the old prepare script, found no CA
 * where the new URL names one, and lost the database. So the exit code is not
 * asked: a plan never resets a host, and a host this apply made is
 * `hostNeedsReset`'s own answer.
 */
export function applyShouldResetHost(action: string, before: HostBeforeApply, after: string | null): boolean {
  return action === 'apply' && hostNeedsReset(before, after);
}

/** `gcloud`'s arguments for that reset. */
export function hostResetArgs(host: string, zone: string, projectId: string): string[] {
  return ['compute', 'instances', 'reset', host, '--zone', zone, '--project', projectId];
}

function list(value: string): string[] {
  return value
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean);
}

function readBackend(): CloudBackend | null {
  if (!existsSync(backendPath())) return null;
  const parsed = JSON.parse(readFileSync(backendPath(), 'utf8')) as Partial<CloudBackend>;
  return parsed.bucket ? { bucket: parsed.bucket, prefix: parsed.prefix || 'openadlc' } : null;
}

function writeBackend(backend: CloudBackend): void {
  writePrivate(backendPath(), `${JSON.stringify(backend, null, 2)}\n`);
}

/**
 * `cloud configure` is often the first command on a laptop that never ran a
 * local install, so nothing had made $OPENADLC_HOME: the settings write
 * failed with ENOENT after every question was answered and the bucket made,
 * and the answers and the new webhook secret were lost.
 */
function ensureHome(): void {
  mkdirSync(openadlcHome(), { recursive: true, mode: 0o700 });
}

/** What `configure` leaves on this machine: the settings and where their bucket is. */
export function writeCloudFiles(vars: Record<string, unknown>, backend: CloudBackend): void {
  writePrivate(tfVarsPath(), `${JSON.stringify(vars, null, 2)}\n`);
  writeBackend(backend);
}

/**
 * The settings hold the webhook secret. `writeFileSync`'s mode applies only to
 * a file it creates, so one already there kept whatever mode it had.
 */
function writePrivate(path: string, text: string): void {
  ensureHome();
  writeFileSync(path, text, { mode: 0o600 });
  chmodSync(path, 0o600);
}

/**
 * What is wrong with the `terraform` on PATH, from what `terraform version
 * -json` answered; null when it is Terraform 1.6 or later. Cloud Shell's
 * /google/bin/terraform is a placeholder that prints install instructions and
 * exits 0, so a plan and an apply run through it "passed" with nothing created.
 */
export function terraformProblem(answer: GcloudResult): string | null {
  const install = 'install Terraform 1.6 or later (https://developer.hashicorp.com/terraform/install), or run infra/gcp/install.sh, which installs it';
  if (answer.code === 127) return `terraform is not installed: ${install}`;
  let version: unknown;
  try {
    version = (JSON.parse(answer.stdout) as { terraform_version?: unknown }).terraform_version;
  } catch {
    version = undefined;
  }
  if (answer.code !== 0 || typeof version !== 'string') {
    return `the terraform on this machine is not Terraform (Cloud Shell's is only a placeholder): ${install}`;
  }
  const [major = 0, minor = 0] = version.split('.').map((part) => Number.parseInt(part, 10));
  if (major < 1 || (major === 1 && minor < 6)) return `this is Terraform ${version}; ${install}`;
  return null;
}

async function terraformReady(): Promise<boolean> {
  const problem = terraformProblem(await capture('terraform', ['version', '-json']));
  if (!problem) return true;
  ui.fail(problem);
  return false;
}

async function run(command: string, args: string[], cwd?: string): Promise<number> {
  return new Promise((resolve) => {
    const child = spawn(command, args, { cwd, stdio: 'inherit' });
    child.on('close', (code) => resolve(code ?? 1));
    child.on('error', () => {
      ui.fail(`${command} is not installed`);
      ui.note(
        command === 'terraform'
          ? 'https://developer.hashicorp.com/terraform/install'
          : 'https://cloud.google.com/sdk/docs/install',
      );
      resolve(127);
    });
  });
}

/** A command's output, kept rather than shown: what `gcloud` answers to a question. */
async function capture(command: string, args: string[], cwd?: string, env?: NodeJS.ProcessEnv): Promise<GcloudResult> {
  return new Promise((resolve) => {
    const child = spawn(command, args, { cwd, stdio: ['ignore', 'pipe', 'pipe'], ...(env ? { env } : {}) });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (chunk: Buffer) => (stdout += chunk.toString()));
    child.stderr.on('data', (chunk: Buffer) => (stderr += chunk.toString()));
    child.on('close', (code) => resolve({ code: code ?? 1, stdout, stderr }));
    child.on('error', () => resolve({ code: 127, stdout, stderr }));
  });
}

/**
 * One of gcloud's configured values — the project, the signed-in account — or
 * undefined when gcloud is missing, not signed in, or has none set. gcloud
 * prints `(unset)` for a property with no value, which is not an answer.
 */
async function gcloudConfigValue(name: string): Promise<string | undefined> {
  const asked = await capture('gcloud', ['config', 'get-value', name]);
  const value = asked.stdout.trim();
  return asked.code === 0 && value && value !== '(unset)' ? value : undefined;
}

/**
 * Runs a command with its output shown as it comes, and keeps the end of it,
 * so a Terraform failure can be said in words after Terraform has said it.
 */
async function runKeeping(command: string, args: string[], cwd?: string): Promise<{ code: number; tail: string }> {
  return new Promise((resolve) => {
    const child = spawn(command, args, { cwd, stdio: ['inherit', 'pipe', 'pipe'] });
    let tail = '';
    const keep = (chunk: Buffer, to: NodeJS.WriteStream) => {
      to.write(chunk);
      tail = (tail + chunk.toString()).slice(-64 * 1024);
    };
    child.stdout.on('data', (chunk: Buffer) => keep(chunk, process.stdout));
    child.stderr.on('data', (chunk: Buffer) => keep(chunk, process.stderr));
    child.on('close', (code) => resolve({ code: code ?? 1, tail }));
    child.on('error', () => {
      ui.fail(`${command} is not installed`);
      resolve({ code: 127, tail });
    });
  });
}

/** One printable line: the shape of every value the module's outputs hold. */
const OUTPUT_SHAPE = /^[\x21-\x7e]{1,256}$/;

/**
 * What a `terraform output -raw` read answered, or null when it answered
 * nothing usable. On a state with no outputs — what an apply that ended in an
 * error leaves behind — `terraform output` exits 0 and prints a multi-line
 * "No outputs found" warning on stdout. That warning was once read back as the
 * host's name, and the reset ran `gcloud compute instances reset '<the whole
 * warning>'` on a host this very apply had made. An answer counts only when it
 * looks like one: the host's name as GCE allows names, anything else one
 * printable line.
 */
export function outputAnswer(name: string, read: { code: number; stdout: string }): string | null {
  if (read.code !== 0) return null;
  const value = read.stdout.trim();
  return (name === 'host_name' ? INSTANCE_NAME : OUTPUT_SHAPE).test(value) ? value : null;
}

/** One of the module's outputs from the state, or null when there is none to use. */
async function outputValue(name: string, dir: string): Promise<string | null> {
  return outputAnswer(name, await capture('terraform', ['output', '-raw', name], dir));
}

/**
 * Whether the project is this install's to set up in: nothing left in it by
 * an earlier install that this one's state does not hold (`cloud-leftovers.ts`).
 * False when something is, said with what to do; true otherwise, including
 * when it could not be checked.
 */
async function freshProject(settled: Record<string, unknown>, dir: string): Promise<boolean> {
  const projectId = typeof settled.project_id === 'string' ? settled.project_id : '';
  const prefix = typeof settled.name_prefix === 'string' ? settled.name_prefix : NAME_PREFIX;
  if (!projectId) return true;
  const state = await capture('terraform', ['state', 'list'], dir);
  if (state.code !== 0) {
    ui.note('could not read the Terraform state, so the project was not checked for an earlier install');
    return true;
  }
  const owned = ownedAddresses(state.stdout);
  ui.step(`checking ${projectId} for an earlier install`);
  const report = await findLeftovers({ projectId, prefix, owned }, (args) => capture('gcloud', args));
  for (const line of report.unchecked) ui.note(`not checked: ${line}`);
  if (report.found.length === 0) return true;
  const [first, ...rest] = leftoversMessage(projectId, report.found);
  ui.fail(first ?? '');
  for (const line of rest) ui.plain(line);
  return false;
}

/**
 * The bucket, made if it is not there: versioned, private, in the install's
 * own project. One that is there is used only when it is all three, or only
 * lacks versioning (`cloud-bucket.ts`). False, said with what to do, otherwise.
 */
async function ensureBucket(backend: CloudBackend, projectId: string, region: string): Promise<boolean> {
  const check = await checkBucket(backend.bucket, projectId, (args) => capture('gcloud', args));
  if (check.state === 'refused') {
    const [first, ...rest] = check.lines;
    ui.fail(first ?? '');
    for (const line of rest) ui.note(line);
    return false;
  }
  if (check.state === 'usable') {
    if (check.versioned) return true;
    ui.step(`turning on versioning for gs://${backend.bucket}`);
    return (await run('gcloud', ['storage', 'buckets', 'update', `gs://${backend.bucket}`, '--versioning'])) === 0;
  }
  ui.step(`creating gs://${backend.bucket} in ${projectId}`);
  const created = await run('gcloud', [
    'storage',
    'buckets',
    'create',
    `gs://${backend.bucket}`,
    `--project=${projectId}`,
    `--location=${region}`,
    '--uniform-bucket-level-access',
    '--public-access-prevention',
  ]);
  if (created !== 0) return false;
  // Versioned, so an apply that goes wrong can be walked back to the state before it.
  return (await run('gcloud', ['storage', 'buckets', 'update', `gs://${backend.bucket}`, '--versioning'])) === 0;
}

/**
 * The settings this install already has: this machine's copy, else the one in
 * the bucket `cloud.backend.json` names. Undefined for a new install, or when
 * neither could be read, which is said with what that means to the caller.
 */
async function existingSettings(unread = 'so this is configured as a new install'): Promise<Record<string, unknown> | undefined> {
  const parse = (text: string, where: string): Record<string, unknown> | undefined => {
    try {
      const vars = JSON.parse(text) as unknown;
      if (vars && typeof vars === 'object' && !Array.isArray(vars)) return vars as Record<string, unknown>;
    } catch {
      // Said below.
    }
    ui.note(`${where} could not be read as settings, ${unread}`);
    return undefined;
  };
  if (existsSync(tfVarsPath())) return parse(readFileSync(tfVarsPath(), 'utf8'), tfVarsPath());
  const backend = readBackend();
  if (!backend) return undefined;
  const remote = remoteTfVars(backend);
  const copied = await capture('gcloud', ['storage', 'cat', remote]);
  if (copied.code !== 0) {
    ui.note(`could not read ${remote}, ${unread}`);
    return undefined;
  }
  return parse(copied.stdout, remote);
}

async function push(backend: CloudBackend): Promise<number> {
  const code = await run('gcloud', ['storage', 'cp', tfVarsPath(), remoteTfVars(backend)]);
  if (code === 0) ui.ok(`settings saved to ${remoteTfVars(backend)}`);
  return code;
}

