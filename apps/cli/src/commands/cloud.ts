/**
 * Asks until there is an answer. `prompt` shows a default in parentheses, and
 * these questions put an example there: Enter took what looked like
 * `openadlc.example.com` and wrote an empty console domain, which was then
 * pushed to the bucket.
 */
export async function askRequired(
  ask: (question: string, fallback?: string) => Promise<string>,
  question: string,
  fallback?: string,
): Promise<string> {
  for (;;) {
    const answer = (await ask(question, fallback ?? '')).trim();
    if (answer) return answer;
    ui.warn('this one needs an answer');
  }
}

/**
 * What the host ran on before an apply: its name, and the module's
 * `host_rollout` (its cloud-init and the database URL), each null when the
 * state had none.
 */
export interface HostBeforeApply {
  host: string | null;
  rollout: string | null;
}

/**
 * A name as GCE allows instance names. Nothing that fails this is a host, and
 * nothing that fails this goes on a gcloud command line.
 */
export const INSTANCE_NAME = /^[a-z]([-a-z0-9]{0,61}[a-z0-9])?$/;

/**
 * Whether an apply has to reset the host. Container-Optimized OS applies
 * cloud-init at boot, and hostd reads the database URL only when it starts: a
 * host that was only restarted ran the old prepare script against the new URL,
 * found no CA where the URL names one, and lost the database. Not for a host
 * this apply made, which booted on the new ones. A host whose state predates
 * `host_rollout` has none before, and is reset once.
 *
 * Only for a host that is known by name: when the outputs could not be read —
 * an apply that ends in an error writes none — there is nothing to decide
 * with, and the host, made or changed by this very apply, boots on the new
 * settings anyway. `outputAnswer` turns everything unusable into null, and a
 * name that is not one is checked again here, the last call before gcloud.
 */
export function hostNeedsReset(before: HostBeforeApply, after: string | null): boolean {
  return before.host !== null && INSTANCE_NAME.test(before.host) && after !== null && before.rollout !== after;
}

/**
 * Whether this command has to reset the host, including an apply that failed.
 *
 * Terraform can commit the new `host_rollout` and then fail on a later
 * resource. The reset ran only after an apply that exited 0, so a host whose
 * database URL had already changed kept the old prepare script, found no CA
 * where the new URL names one, and lost the database. So the exit code is not
 * asked: a plan never resets a host, and a host this apply made is
 * `hostNeedsReset`'s own answer.
 */
export function applyShouldResetHost(action: string, before: HostBeforeApply, after: string | null): boolean {
  return action === 'apply' && hostNeedsReset(before, after);
}

/** `gcloud`'s arguments for that reset. */
export function hostResetArgs(host: string, zone: string, projectId: string): string[] {
  return ['compute', 'instances', 'reset', host, '--zone', zone, '--project', projectId];
}

