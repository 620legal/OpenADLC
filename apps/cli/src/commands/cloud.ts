/**
 * `openadlc cloud members [add EMAIL…]`, returning its exit code.
 *
 * Who IAP admits to the console, and letting someone else in. Settings →
 * Users decides what a person may do; this list decides whether they reach
 * the console at all, and it is all the module's authoritative binding
 * keeps after an apply — a grant added by hand with gcloud is deleted by
 * the next one. The console's Users page names this command when it lists
 * an address IAP does not admit.
 */
export async function membersCommand(rest: readonly string[], noApply: boolean, runners: MembersRunners): Promise<number> {
  const backend = runners.backend();
  // The settings as `configure` reads them: a machine that never ran
  // `configure` or `pull` has only the bucket's copy, and refusing it there
  // sent the admin to pull an install they already had.
  const vars = backend ? await runners.settings() : undefined;
  if (!backend || !vars) {
    ui.fail('this machine has no cloud configuration');
    ui.note('openadlc cloud configure, or openadlc cloud pull --bucket <name> for an install that exists');
    return 1;
  }
  const current = Array.isArray(vars.console_members) ? vars.console_members.filter((member): member is string => typeof member === 'string') : [];
  const [verb, ...typed] = rest;

  if (verb === undefined) {
    ui.heading('Who IAP admits to the console (console_members)');
    if (current.length === 0) ui.warn('nobody: console_members is empty, so IAP turns everyone away');
    for (const member of current) ui.step(member);
    ui.note('from this install’s settings; IAP enforces what the last openadlc cloud apply applied');
    return 0;
  }
  if (verb !== 'add' || typed.length === 0) {
    if (verb === 'add') ui.fail('whom? openadlc cloud members add you@example.com');
    else ui.fail(`unknown members command: ${verb}`);
    ui.note('try: openadlc cloud members, or openadlc cloud members add EMAIL [EMAIL…] [--no-apply]');
    return 2;
  }
  const refused = typed.map(invalidMember).filter((reason): reason is string => reason !== null);
  if (refused.length > 0) {
    for (const reason of refused) ui.fail(reason);
    ui.note('nothing was changed');
    return 2;
  }

  const { members, added, already } = withAddedMembers(current, typed);
  for (const member of already) ui.note(`${member} is already admitted`);
  if (added.length === 0) {
    // The list can name someone IAP does not admit yet: an earlier add whose
    // push or apply failed, or that ran with --no-apply, wrote the file first.
    // Adding them again changes nothing, so say what does.
    ui.ok('nothing to change');
    ui.step('if IAP still turns them away, the change never went out: openadlc cloud apply');
    return 0;
  }
  runners.write({ ...vars, console_members: members }, backend);
  ui.ok(`console_members now admits ${added.join(', ')}`);
  const pushed = await runners.push(backend);
  if (pushed !== 0) return pushed;
  if (noApply) {
    ui.step('next: openadlc cloud apply — IAP admits them only once it runs');
    return 0;
  }
  // The apply is what makes IAP enforce the new list; without it the file
  // and the bucket say one thing and the install another.
  return runners.apply();
}

/** What `afterTerraform` runs, passed in so a test can stand in for each. */
export interface AfterTerraformRunners {
  run: (command: string, args: string[]) => Promise<number>;
  outputValue: (name: string) => Promise<string | null>;
  push: () => Promise<number>;
}

/**
 * What `plan` or `apply` does once Terraform has exited with `code`: saves
 * the settings a successful apply used, resets the host when what it boots on
 * changed, and lists what is left to do by hand.
 */
export async function afterTerraform(
  action: string,
  code: number,
  before: HostBeforeApply,
  settled: Record<string, unknown>,
  runners: AfterTerraformRunners,
): Promise<void> {
  if (code === 0 && action === 'apply') {
    // What was applied is what the next operator should find.
    await runners.push();
  }

  // Outside the success branch: a failed apply can already have committed
  // the new rollout, and the host is then on the old prepare script.
  const afterRollout = action === 'apply' ? await runners.outputValue('host_rollout') : null;
  // What the state knew before, only when it is a host: nothing else may be
  // reset, named in a message, or suggested as a command to run.
  const host = before.host !== null && INSTANCE_NAME.test(before.host) ? before.host : null;
  // The module's default, for settings that never named a zone.
  const zone = typeof settled.zone === 'string' && settled.zone ? settled.zone : 'us-central1-a';
  const projectId = String(settled.project_id ?? '');
  let resetMissed: string | null = null;
  if (action === 'apply' && afterRollout === null) {
    // Nothing usable to decide with, and no deciding on a warning. Nor will a
    // later apply decide it, as this note once said: it compares only its own
    // before and after, so a rollout this apply committed reads the same on
    // both sides of the next one, and the host stays on the old prepare script
    // and loses the database. So a known host gets its reset to run by hand.
    const unread =
      code === 0
        ? "Terraform's host_rollout output could not be read after the apply"
        : 'Terraform left no outputs to read, typically because the apply ended in an error';
    const again = code === 0 ? '' : '. Run openadlc cloud apply again to finish the apply';
    ui.plain();
    if (host) {
      ui.note(
        `${unread}: whether ${host} must be reset was not decided, and a later apply will not decide it, since it compares only its own before and after${again}`,
      );
      resetMissed = `gcloud ${hostResetArgs(host, zone, projectId).join(' ')}   (if this apply changed the host's cloud-init or database settings: the host runs on the old ones until it is reset)`;
    } else {
      ui.note(
        code === 0
          ? `${unread}, and no host was known before it: nothing was reset. Check the outputs with openadlc cloud output`
          : `${unread}: run openadlc cloud apply again`,
      );
    }
  }
  if (host && applyShouldResetHost(action, before, afterRollout)) {
    const args = hostResetArgs(host, zone, projectId);
    ui.plain();
    ui.note(`the host's cloud-init or database settings changed: resetting ${host} so it boots on them`);
    if ((await runners.run('gcloud', args)) !== 0) {
      resetMissed = `gcloud ${args.join(' ')}   (the host still runs on the old settings until it is reset)`;
    }
  }

  if (code === 0 && action === 'apply') {
    const steps = postApplySteps(tfVarsPath(), typeof settled.console_domain === 'string' ? settled.console_domain : '');
    if (resetMissed) steps.unshift(resetMissed);
    ui.plain();
    ui.heading('Still to do by hand');
    for (const step of steps) ui.step(step);
  } else if (resetMissed) {
    ui.note(resetMissed);
  }
}

