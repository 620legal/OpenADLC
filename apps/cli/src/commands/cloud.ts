/**
 * Every answer `configure` no longer asks for. A flag wins, then the install's
 * own settings, then what infra/gcp/install.sh found (`configureDefaults`),
 * then gcloud's own configuration; what none of them name is the module's to
 * default. `configure` used to ask about ten questions, and for a first-time
 * install every one of them already had its answer somewhere on this list —
 * the GitHub pair is deliberately empty, because the console's walkthrough
 * collects the organization and creates the app, and the bridge prefers what
 * the walkthrough stored over these seeds.
 */
export function settledAnswers(
  flags: ConfigureFlags,
  existing: Record<string, unknown> | undefined,
  offered: ReturnType<typeof configureDefaults>,
  gcloud: { project?: string; account?: string },
): {
  projectId: string | null;
  region: string;
  zone: string;
  organization: string;
  githubClientId: string;
  humans: string[];
  consoleDomain: string;
  /** `--members`, which answers the one question without asking it. */
  membersGiven: string | null;
  membersDefault?: string;
  notificationChannels: string[];
} {
  const region = flags.region ?? shown(existing, 'region') ?? offered.region ?? 'us-central1';
  // A kept zone has to be in the settled region: `--region` on an install
  // whose settings name a zone elsewhere would otherwise plan a host in a
  // zone the region does not have.
  const keptZone = shown(existing, 'zone');
  const membersDefault =
    shown(existing, 'console_members') ?? offered.consoleMembers ?? (gcloud.account ? `user:${gcloud.account}` : undefined);
  return {
    projectId: flags.project ?? shown(existing, 'project_id') ?? offered.projectId ?? gcloud.project ?? null,
    region,
    zone: flags.zone ?? (keptZone?.startsWith(`${region}-`) ? keptZone : `${region}-a`),
    organization: flags.organization ?? shown(existing, 'github_organization') ?? '',
    githubClientId: flags.clientId ?? shown(existing, 'github_app_client_id') ?? '',
    humans: list(shown(existing, 'humans') ?? ''),
    // Empty is not "no console": the module serves it on the install's own
    // address under nip.io until a domain of the operator's own is set.
    consoleDomain: flags.domain ?? shown(existing, 'console_domain') ?? offered.domain ?? '',
    membersGiven: flags.members ?? null,
    ...(membersDefault ? { membersDefault } : {}),
    notificationChannels: list(flags.channels ?? shown(existing, 'notification_channels') ?? ''),
  };
}

/**
 * Who may take over a terminal when nobody is named: the console members that
 * are people. On a fresh install that is the one person setting it up, which
 * is who a take-over is for; a `group:` or `domain:` member is not carried
 * over, because take-over is a shell inside a bot's computer and a group is
 * wider than the list that may merely read the board should ever be.
 */
export function defaultOperators(members: string[]): string[] {
  return members.filter((member) => member.startsWith('user:'));
}

/**
 * The console members as IAM spells them, from however a person answers the
 * one question. The natural answer is a bare email, and taken as typed it was
 * no IAM member at all: IAP would admit nobody, and `consoleUsers` saw no
 * `user:` either, so the install also had no admin and said so. A bare answer
 * is a person, `user:<email>`; one with a type (`user:`, `group:`, `domain:`,
 * `serviceAccount:`) is kept as typed.
 */
export function normalizedMembers(members: string[]): string[] {
  return members.map((member) => (member.includes(':') ? member : `user:${member}`));
}

const EMAIL = /^[^\s@]+@[^\s@]+$/;

/**
 * Why something typed after `cloud members add` cannot be an IAM member, or
 * null. Taken as typed, a stray word became `user:<word>`: IAP admitted
 * nobody by it, the apply still went through, and nothing said which entry
 * was the dud.
 */
export function invalidMember(typed: string): string | null {
  const member = typed.includes(':') ? typed : `user:${typed}`;
  const colon = member.indexOf(':');
  const kind = member.slice(0, colon);
  const name = member.slice(colon + 1);
  if (kind === 'user' || kind === 'group' || kind === 'serviceAccount') {
    return EMAIL.test(name) ? null : `${typed} is not an email address`;
  }
  if (kind === 'domain') {
    return name && !name.includes('@') && !/\s/.test(name) ? null : `${typed} does not name a domain (domain:example.com)`;
  }
  return `${typed} is not an IAM member: user:, group:, domain: or serviceAccount:`;
}

/**
 * `console_members` with the typed members admitted: each as IAM spells it,
 * added once. A member the list already has — however it capitalises the
 * address, since IAP's sign-in does not care — is said rather than doubled.
 *
 * Both sides are compared as IAM spells them. Settings written before
 * `configure` added the prefix can hold a bare `jane@example.com`, and
 * compared as stored it matched neither `jane@example.com` nor
 * `user:jane@example.com`, so the same person went in twice.
 */
export function withAddedMembers(
  current: readonly string[],
  typed: readonly string[],
): { members: string[]; added: string[]; already: string[] } {
  const members = [...current];
  const added: string[] = [];
  const already: string[] = [];
  const identity = (member: string): string => (normalizedMembers([member.trim()])[0] as string).toLowerCase();
  for (const one of normalizedMembers([...typed])) {
    if (members.some((member) => identity(member) === identity(one))) already.push(one);
    else {
      members.push(one);
      added.push(one);
    }
  }
  return { members, added, already };
}

/**
 * The arguments after `cloud members`, with flags and their values passed
 * over: `members add a@b.com --provider gcp` adds a@b.com, not gcp too.
 */
export function memberArguments(argv: readonly string[]): string[] {
  const positionals: string[] = [];
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index] as string;
    if (!argument.startsWith('-')) {
      positionals.push(argument);
      continue;
    }
    // The one value-taking flag every cloud command shares, written with a
    // space; written as --provider=gcp it is one argument and skips itself.
    if (argument === '--provider') index += 1;
  }
  return positionals;
}

function shown(existing: Record<string, unknown> | undefined, key: string): string | undefined {
  const value = existing?.[key];
  if (typeof value === 'string' && value) return value;
  if (Array.isArray(value) && value.length > 0) return value.filter((entry) => typeof entry === 'string').join(',');
  return undefined;
}

/**
 * GitHub's own spelling of a repository, for the deployer.
 *
 * The deployer's identity condition (`infra/gcp/deployer.tf`) compares the
 * token's `repository` claim, which GitHub fills with the canonical name, as a
 * string: `exampleco/deploys` typed for `ExampleCo/Deploys` refused every
 * deploy at token exchange, with nothing saying case was why. GitHub's lookup
 * ignores case, so it answers with the right spelling. A repository it will
 * not show without a sign-in, a private one, is kept as typed.
 *
 * The same answer carries the repository's numeric id and its owner's, which
 * the provider admits it by: a name is freed by a rename or a transfer and
 * can be taken by someone else, an id cannot.
 */
export async function canonicalRepository(
  typed: string,
  lookup: (url: string) => Promise<{ ok: boolean; json(): Promise<unknown> }> = (url) =>
    fetch(url, { headers: { accept: 'application/vnd.github+json' } }),
): Promise<{ name: string; checked: boolean; id?: string; ownerId?: string }> {
  if (!/^[A-Za-z0-9-]+\/[A-Za-z0-9._-]+$/.test(typed)) return { name: typed, checked: false };
  try {
    const answer = await lookup(`https://api.github.com/repos/${typed}`);
    if (!answer.ok) return { name: typed, checked: false };
    const repo = (await answer.json()) as { full_name?: unknown; id?: unknown; owner?: { id?: unknown } | null };
    if (typeof repo.full_name !== 'string' || repo.full_name.toLowerCase() !== typed.toLowerCase()) return { name: typed, checked: false };
    const id = numericId(repo.id);
    const ownerId = numericId(repo.owner?.id);
    return { name: repo.full_name, checked: true, ...(id && ownerId ? { id, ownerId } : {}) };
  } catch {
    return { name: typed, checked: false };
  }
}

/** A GitHub id as the token's claims carry it: decimal digits, as a string. */
function numericId(value: unknown): string | undefined {
  if (typeof value === 'number' && Number.isSafeInteger(value) && value > 0) return String(value);
  if (typeof value === 'string' && /^[0-9]+$/.test(value)) return value;
  return undefined;
}

