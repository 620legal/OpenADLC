type Provider = (typeof PROVIDERS)[number];

/**
 * Where an install's Terraform state lives, and next to it the install's own
 * settings.
 *
 * The module is OpenADLC's and ships in this repository; the values that make it
 * one install — the project, the domain, the organization, who may open the
 * console, the webhook secret — are not, and must not be. They used to exist
 * only as `$FLEETADLC_HOME/cloud.tfvars.json` on whichever machine ran `configure`,
 * with the state beside the module in the checkout: the next operator, or the
 * same one on a new laptop, had neither. Both now live in a bucket in the
 * install's own project, so any machine with access can `fleetadlc cloud pull` and
 * carry on.
 */
export interface CloudBackend {
  bucket: string;
  prefix: string;
}

export interface CloudConfig {
  provider: Provider;
  projectId: string;
  region: string;
  zone: string;
  organization: string;
  githubClientId: string;
  humans: string[];
  consoleDomain: string;
  bridgeImage: string;
  consoleImage: string;
  /** The host's own image, and the image each bot's container runs. */
  hostdImage: string;
  botImage: string;
  consoleMembers: string[];
  /** The console's first admins, written as `admin_emails`; empty, and the `user:` console members are. */
  adminEmails: string[];
  operators: string[];
  /** Generated by the first `configure` and kept in cloud.tfvars.json after; GitHub signs deliveries with it. */
  webhookSecret: string;
  /** owner/name of a repository whose workflow may roll out new images; empty for none. */
  deployerRepository?: string;
  /**
   * The deployer repository's numeric id and its owner's, which the identity
   * provider admits it by, and the one workflow file in it that may deploy.
   * Written only with a deployer repository.
   */
  deployerRepositoryId?: string;
  deployerRepositoryOwnerId?: string;
  deployerWorkflow?: string;
  /** Cloud Monitoring channels the alerts go to; none, and an alert notifies nobody. */
  notificationChannels?: string[];
}

const TFVARS = 'cloud.tfvars.json';

/** The module's default for `deployer_workflow`. */
export const DEFAULT_DEPLOYER_WORKFLOW = '.github/workflows/deploy.yml';

/**
 * Every resource the module makes is named from this. Settings written before
 * the rename to FleetADLC carry no `name_prefix`, and their resources were made
 * under the module's old default, `fleet` — applying them with the new default
 * would replace the network, the database and the host rather than update them.
 */
export const NAME_PREFIX = 'fleetadlc';
export const LEGACY_NAME_PREFIX = 'fleet';

/** The settings, with the name the install's resources already have pinned in. */
export function pinNamePrefix(vars: Record<string, unknown>): { vars: Record<string, unknown>; pinned: boolean } {
  if (typeof vars.name_prefix === 'string' && vars.name_prefix.length > 0) return { vars, pinned: false };
  return { vars: { ...vars, name_prefix: LEGACY_NAME_PREFIX }, pinned: true };
}
const BACKEND = 'cloud.backend.json';

function tfVarsPath(): string {
  return join(fleetHome(), TFVARS);
}

function backendPath(): string {
  return join(fleetHome(), BACKEND);
}

function moduleDir(config: InstallConfig, provider: Provider): string {
  return join(config.repoRoot, 'infra', provider);
}

/** The module's inputs, by the names its variables.tf declares. */
export function tfVars(cloud: CloudConfig, hostdPort: number): Record<string, unknown> {
  return {
    project_id: cloud.projectId,
    region: cloud.region,
    zone: cloud.zone,
    github_organization: cloud.organization,
    github_app_client_id: cloud.githubClientId,
    humans: cloud.humans,
    console_domain: cloud.consoleDomain,
    bridge_image: cloud.bridgeImage,
    console_image: cloud.consoleImage,
    // Both are required by the module and neither was written here, so
    // `terraform apply` stopped to ask for them — and `bot_image` had no
    // asking to do, because nothing provisioned a bot image at all.
    hostd_image: cloud.hostdImage,
    bot_image: cloud.botImage,
    console_members: cloud.consoleMembers,
    admin_emails: cloud.adminEmails,
    operators: cloud.operators,
    webhook_secret: cloud.webhookSecret,
    hostd_port: hostdPort,
    name_prefix: NAME_PREFIX,
    ...(cloud.deployerRepository
      ? {
          deployer_repository: cloud.deployerRepository,
          deployer_repository_id: cloud.deployerRepositoryId ?? '',
          deployer_repository_owner_id: cloud.deployerRepositoryOwnerId ?? '',
          deployer_workflow: cloud.deployerWorkflow || DEFAULT_DEPLOYER_WORKFLOW,
        }
      : {}),
    ...(cloud.notificationChannels?.length ? { notification_channels: cloud.notificationChannels } : {}),
  };
}

/**
 * The settings `configure` writes, over the ones the install already has.
 *
 * `configure` once built them from its answers alone, with a new webhook
 * secret each run: run again on a live install, to set the deployer, it
 * rotated the secret at the next apply so GitHub's deliveries failed
 * verification, dropped settings added by hand such as `admin_emails`, and on
 * an install from before the rename reset `name_prefix` to `fleetadlc`, so
 * plan looked at an empty state. Now the secret is made only when there is
 * none, everything not asked about carries over, and the prefix is the one the
 * install's resources already have.
 */
export function configuredVars(
  existing: Record<string, unknown> | undefined,
  answers: Omit<CloudConfig, 'webhookSecret'>,
  hostdPort: number,
  secret: () => string,
): Record<string, unknown> {
  const kept = typeof existing?.webhook_secret === 'string' && existing.webhook_secret ? existing.webhook_secret : secret();
  const vars = tfVars({ ...answers, webhookSecret: kept }, hostdPort);
  if (!existing) return vars;
  // tfVars always writes the new prefix, so the old one is put back after the merge.
  return pinNamePrefix({ ...existing, ...vars, name_prefix: existing.name_prefix }).vars;
}

/**
 * The console members that name a person, as bare addresses: the default for
 * the first admins. A `group:` or `domain:` member names nobody the bridge can
 * make admin, so an install that lets people in only that way had no admin.
 */
export function consoleUsers(members: string[]): string[] {
  return members.filter((member) => member.startsWith('user:')).map((member) => member.slice('user:'.length)).filter(Boolean);
}

/**
 * What `configure` says when the first admins name nobody. It still writes
 * the settings: the install can be deployed, and the bridge refuses every
 * visitor with "no admin is configured" until this is fixed.
 */
export function noAdminWarning(adminEmails: string[], settingsPath: string): string | null {
  if (adminEmails.length > 0) return null;
  return `the console will have no admin: nobody is named, so every visitor is refused. Add "admin_emails": ["you@example.com"] to ${settingsPath} and run: fleetadlc cloud apply`;
}

